#!/usr/bin/env node
// Builds the single-file CLI served at https://agent-guild.com/agent-guild.mjs
// (AgentGuildApp/public/agent-guild.mjs) from agent-guild.mjs. A fresh agent
// downloads that one file to /tmp and runs it, so the pure sibling modules it
// imports are inlined here. solana-escrow.mjs stays a lazy import(): it needs
// @coral-xyz/anchor, so gig-order escrow works only from the npm package.
//
//   node build-standalone.mjs           write AgentGuildApp/public/agent-guild.mjs
//   node build-standalone.mjs --check   exit 1 if that file is stale
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const OUT_PATH = join(here, "..", "..", "AgentGuildApp", "public", "agent-guild.mjs");

/** Sibling modules with only node: imports; each is inlined at its import line. */
const INLINE = ["identity-vault-crypto.mjs", "mod-tools.mjs", "hl-mode.mjs"];

const IMPORT_RE = /^import\s+(.+?)\s+from\s+"([^"]+)";\s*$/gm;

/** `import X from "m"` / `import { a, b as c } from "m"` → const bindings from a dynamic import. */
function importToConst(clause, spec) {
  if (/^\{.*\}$/.test(clause)) return `const ${clause.replace(/\bas\b/g, ":")} = await import("${spec}");`;
  if (/^\w+$/.test(clause)) return `const ${clause} = (await import("${spec}")).default;`;
  throw new Error(`build-standalone: unsupported import clause "${clause}" from ${spec}`);
}

/** One module as a scoped block that defines only the names it exports. */
function inlineModule(file, names) {
  let body = readFileSync(join(here, file), "utf8");
  body = body.replace(IMPORT_RE, (_, clause, spec) => {
    if (!spec.startsWith("node:")) throw new Error(`build-standalone: ${file} imports ${spec}; only node: imports can be inlined`);
    return importToConst(clause, spec);
  });
  const exported = [...body.matchAll(/^export\s+(?:async\s+function|function|const|let|class)\s+(\w+)/gm)].map((m) => m[1]);
  body = body.replace(/^export\s+/gm, "");
  for (const n of names) {
    if (!exported.includes(n)) throw new Error(`build-standalone: ${file} does not export ${n}`);
  }
  const indented = body.trimEnd().split("\n").map((l) => (l ? `  ${l}` : l)).join("\n");
  return `// --- inlined from ./${file} (build-standalone.mjs) ---\nconst { ${names.join(", ")} } = await (async () => {\n${indented}\n  return { ${names.join(", ")} };\n})();\n// --- end ./${file} ---`;
}

export function buildStandalone() {
  const src = readFileSync(join(here, "agent-guild.mjs"), "utf8");
  const seen = new Set();
  const out = src.replace(IMPORT_RE, (line, clause, spec) => {
    const file = spec.replace(/^\.\//, "");
    if (!spec.startsWith("./")) return line;
    if (!INLINE.includes(file)) throw new Error(`build-standalone: agent-guild.mjs statically imports ${spec}; inline it or load it lazily`);
    const names = clause.replace(/^\{|\}$/g, "").split(",").map((s) => s.trim()).filter(Boolean);
    if (names.some((n) => /\sas\s/.test(n))) throw new Error(`build-standalone: rename imports from ${spec} aren't supported`);
    seen.add(file);
    return inlineModule(file, names);
  });
  for (const f of INLINE) if (!seen.has(f)) throw new Error(`build-standalone: agent-guild.mjs no longer imports ./${f}; drop it from INLINE`);
  const flag = /^const STANDALONE = false;$/m;
  if ((out.match(new RegExp(flag, "gm")) || []).length !== 1) throw new Error("build-standalone: expected exactly one `const STANDALONE = false;` in agent-guild.mjs");
  return out.replace(flag, "const STANDALONE = true;").replace(/^(#!.*\n)?/, (shebang) => `${shebang}// GENERATED by AgentGuildConnect/scripts/build-standalone.mjs from agent-guild.mjs — edit the source, then rebuild.\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const built = buildStandalone();
  let current = "";
  try { current = readFileSync(OUT_PATH, "utf8"); } catch { /* first build */ }
  if (process.argv.includes("--check")) {
    if (current !== built) {
      console.error(`${OUT_PATH} is stale. Run: node AgentGuildConnect/scripts/build-standalone.mjs`);
      process.exit(1);
    }
    console.log("agent-guild.mjs is up to date");
  } else {
    writeFileSync(OUT_PATH, built);
    console.log(`Wrote ${OUT_PATH} (${built.length} bytes)`);
  }
}
